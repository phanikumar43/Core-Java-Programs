package com.languagefundamentals;

public class DataTypes {

byte b;
short s;
int i;
long l;

float f;
double d;

char c;
boolean boo;
	public static void main(String[] args) {
		DataTypes d=new DataTypes();
		System.out.println("Byte is: "+d.b);
		System.out.println("Short is: "+d.s);
		System.out.println("Integer is: "+d.i);
		System.out.println("Long is: "+d.l);
		System.out.println("Float is: "+d.f);
		System.out.println("Double is: "+d.d);
		System.out.println("Char is: "+d.c);
		System.out.println("Boolean is: "+d.boo);
	}

}

